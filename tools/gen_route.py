"""Writes the route table sources into the given folder (build output, not committed)."""
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
out.mkdir(parents=True, exist_ok=True)
(out / "route_table.h").write_text("""/* Generated by tools/gen_route.py - DO NOT EDIT */
#ifndef ROUTE_TABLE_H
#define ROUTE_TABLE_H
int route_lookup(const int *table, int id);
#endif
""")
(out / "route_table.c").write_text("""/* Generated by tools/gen_route.py - DO NOT EDIT */
#include "route_table.h"

int route_lookup(const int *table, int id)
{
    return table[id]; /* CRASH gen: NULL table, SIGSEGV (generated code) */
}
""")
